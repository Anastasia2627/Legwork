import {test,expect} from '@playwright/test';

test('Owner publishes an approved Mentorship quote, student sees its immutable order; owner unpublishes',async({page},testInfo)=>{
 const email='mentor-offer-'+testInfo.project.name+'-'+Date.now()+'@example.test';
 await page.goto('/#/login');
 await page.locator('#authForm [name="email"]').fill('Admin');
 await page.locator('#authForm [name="password"]').fill('LegworkTestAdminPassword-2026-only');
 await page.locator('#authForm button[type="submit"]').click();
 await expect(page).toHaveURL(/#\/account/);
 await page.locator('.cabinet-nav [data-tab="admin"]').click();
 const offer=page.locator('.admin-mentor-offers [data-mentor-offer="Basic"]');
 await expect(offer).toBeVisible();
 await offer.locator('[name="price_usd_cents"]').fill('2500');
 await offer.locator('[name="turnaround_business_days"]').fill('7');
 await offer.locator('[name="published"]').check();
 page.once('dialog',dialog=>dialog.accept());
 await offer.locator('button[type="submit"]').click();
 await expect(page.locator('#toast')).toContainText('Mentorship terms saved');
 await page.goto('/#/mentorship');
 await expect(page.locator('.ref-prices')).toContainText('$25.00 USD');
 await page.goto('/#/register');
 await page.locator('#authForm [name="name"]').fill('Mentorship Offer Student');
 await page.locator('#authForm [name="email"]').fill(email);
 await page.locator('#authForm [name="password"]').fill('MentorshipOfferStudentPassword-2026');
 await page.locator('#authForm button[type="submit"]').click();
 await expect(page).toHaveURL(/#\/account/);
 await page.goto('/#/mentorship');
 const form=page.locator('#mentorshipForm');
 await form.locator('[name="video_url"]').fill('https://example.org/secret-private-mentorship-video');
 await form.locator('[name="goals"]').fill('Learn stronger transitions');
 await form.locator('button[type="submit"]').click();
 await expect(page).toHaveURL(/#\/account/);
 await page.locator('.cabinet-nav [data-tab="reviews"]').click();
 await expect(page.locator('.cabinet-main')).toContainText('25.00 USD · 7 business days after payment confirmation');
 await expect(page.locator('.cabinet-main')).toContainText('7 business days after payment confirmation');
 await page.locator('.cabinet-nav [data-tab="overview"]').click();
 await expect(page.locator('.payment-order-list')).toContainText('mentorship');
 await expect(page.locator('.payment-order-list input[data-pay-order]')).toBeDisabled();
 // Restore the school preview to unquoted offers, leaving no fake production terms.
 await page.goto('/#/login');
 await page.locator('#authForm [name="email"]').fill('Admin');
 await page.locator('#authForm [name="password"]').fill('LegworkTestAdminPassword-2026-only');
 await page.locator('#authForm button[type="submit"]').click();
 await page.locator('.cabinet-nav [data-tab="admin"]').click();
 const after=page.locator('.admin-mentor-offers [data-mentor-offer="Basic"]');
 await expect(after).toBeVisible();
 await after.locator('[name="published"]').uncheck();
 await after.locator('button[type="submit"]').click();
 await expect(page.locator('#toast')).toContainText('Mentorship terms saved');
 await page.goto('/#/mentorship');
 await expect(page.locator('.ref-prices')).toContainText('Price and response time confirmed before payment');
});
